-- 1. CREACIÓN DE ESTRUCTURA (DDL)
CREATE TABLE categorias (
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR2(50) NOT NULL
);

CREATE TABLE productos (
    id_producto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria NUMBER REFERENCES categorias(id_categoria),
    nombre_producto VARCHAR2(100) NOT NULL,
    talla NUMBER(3,1) NOT NULL,
    precio NUMBER(10,2) NOT NULL,
    stock NUMBER DEFAULT 0
);

-- 2. PROCEDIMIENTO ALMACENADO (Lógica de Negocio en PL/SQL)
-- Este procedimiento automatiza el proceso de venta y descuenta el stock de forma segura.
CREATE OR REPLACE PROCEDURE registrar_venta(
    p_id_producto IN NUMBER,
    p_cantidad IN NUMBER
) AS
    v_stock_actual NUMBER;
BEGIN
    -- Validar existencia del producto y obtener stock actual
    SELECT stock INTO v_stock_actual 
    FROM productos 
    WHERE id_producto = p_id_producto;

    -- Lógica de validación
    IF v_stock_actual >= p_cantidad THEN
        -- Descontar inventario
        UPDATE productos 
        SET stock = stock - p_cantidad 
        WHERE id_producto = p_id_producto;
        
        DBMS_OUTPUT.PUT_LINE('Éxito: Venta registrada. Stock actualizado correctamente.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Error: Stock insuficiente para realizar la venta.');
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Error: El producto ingresado no existe en el sistema.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Error crítico en el sistema: ' || SQLERRM);
END;
